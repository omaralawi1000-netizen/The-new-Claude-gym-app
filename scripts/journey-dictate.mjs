// Add food → dictate (Groq Whisper mocked): thread listens, "Transcribing…", words land in the field.
import { launch, wait, skipOnboarding } from './lib.mjs';
import assert from 'node:assert/strict';
const { b, p, errors } = await launch({});
await p.route('**/audio/transcriptions', async (r) => { await new Promise((x) => setTimeout(x, 1500)); await r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ text: 'two eggs and a slice of toast', language: 'english', segments: [{ text: 'two eggs and a slice of toast', no_speech_prob: 0.01, avg_logprob: -0.2, compression_ratio: 1.1 }] }) }); });
await p.goto('http://127.0.0.1:5173/'); await wait(p, 1000);
await skipOnboarding(p);
await p.evaluate(() => localStorage.setItem('aven.keys', JSON.stringify({ groq: 'gsk_test' })));
await p.reload(); await wait(p, 1200);
await p.locator('.tabbar').getByRole('button', { name: 'Food', exact: true }).click(); await wait(p, 700);
await p.getByRole('button', { name: /^Add to / }).first().click(); await wait(p, 900);
await p.screenshot({ path: 'shots/dict-pre.png' });
const mic = p.locator('.dict-mic');
assert(await mic.isVisible(), 'mic button is in the field');
await p.screenshot({ path: 'shots/dict-0-idle.png' });
await mic.click(); await wait(p, 1800);
assert(await p.locator('.dict-listen').count() === 1, 'listening');
const op = await p.locator('.dt-a').evaluate((e) => +getComputedStyle(e).opacity);
console.log('thread opacity while listening', op); assert(op > 0.3, 'thread lit');
await p.screenshot({ path: 'shots/dict-1-listening.png' });
await mic.click(); await wait(p, 1000);
assert(await p.locator('.dict-proc').count() === 1, 'transcribing');
await p.screenshot({ path: 'shots/dict-2-transcribing.png' });
await wait(p, 2200);
assert.equal(await p.getByPlaceholder('Search foods and brands').inputValue(), 'two eggs and a slice of toast');
assert(await p.locator('.dict-listen, .dict-proc').count() === 0, 'back to idle');
const end = await p.locator('.dt-a').evaluate((e) => +getComputedStyle(e).opacity);
assert(end === 0, 'thread gone after landing');
await p.screenshot({ path: 'shots/dict-3-landed.png' });
await b.close();
const real = errors.filter((e) => !/Failed to load resource/.test(e)); assert.equal(real.length, 0, real.join('\n'));
console.log('dictate journey OK');
